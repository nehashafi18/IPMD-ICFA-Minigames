# ── Background removal ──────────────────────────────────────────────────────────
def remove_background(pil_img: Image.Image, **_) -> Image.Image:
    """Neural background removal via rembg — handles gradients and soft edges."""
    from rembg import remove as rembg_remove
    return rembg_remove(pil_img.convert('RGBA'))


def pad_object(rgba: Image.Image, pad_fraction: float = 0.12) -> Image.Image:
    """
    Crop to the non-transparent bounding box, add uniform padding, then make
    the canvas square by centering the object in a square of side = max(w, h).
    Square canvas is required because the game renders objects into a square
    item.w × item.h box — non-square canvases cause non-uniform stretch.
    """
    bbox = rgba.getbbox()
    if not bbox:
        return rgba
    cropped = rgba.crop(bbox)
    cw, ch = cropped.size
    pad = max(int(max(cw, ch) * pad_fraction), 8)
    inner_w = cw + pad * 2
    inner_h = ch + pad * 2
    side = max(inner_w, inner_h)          # force square
    off_x = (side - inner_w) // 2
    off_y = (side - inner_h) // 2
    out = Image.new('RGBA', (side, side), (0, 0, 0, 0))
    out.paste(cropped, (pad + off_x, pad + off_y))
    return out


# ── SD call ─────────────────────────────────────────────────────────────────────
def call_sd(prompt: str, negative: str, seed: int,
            width: int = 512, height: int = 512,
            upscale: int = 1) -> str:
    """
    POST to the SD backend, return the local path of the saved output file.
    Raises on connection error or non-2xx response.
    """
    payload = {
        "prompt":          prompt,
        "negative_prompt": negative,
        "width":           width,
        "height":          height,
        "steps":           40,
        "cfg_scale":       7.0,
        "sampler":         "DPM++ 2M Karras",
        "upscale_factor":  upscale,
        "seed":            seed,
    }
    last_err = None
    for attempt in range(1, 4):
        try:
            r = requests.post(SD_URL, json=payload, timeout=900)
            if r.status_code == 500:
                last_err = f"500 Server Error (attempt {attempt}/3)"
                print(f"  ! SD returned 500 — waiting 25s before retry…")
                time.sleep(25)
                continue
            r.raise_for_status()
            last_err = None
            break
        except requests.exceptions.ConnectionError:
            raise RuntimeError(
                f"SD backend not reachable at {SD_URL}\n"
                "  Start it: cd sd-backend && uvicorn app:app --reload --port 8000"
            )
        except requests.exceptions.ReadTimeout:
            raise RuntimeError(
                f"SD backend timed out after 900s — model may have crashed. "
                "Check uvicorn logs and restart if needed."
            )
    if last_err:
        raise RuntimeError(f"SD backend failed after 3 attempts: {last_err}")
    data = r.json()
    return os.path.join(SCRIPT_DIR, "outputs", data["filename"])


# ── Generators ──────────────────────────────────────────────────────────────────
def generate_background(name: str, force: bool = False) -> None:
    spec = BACKGROUNDS[name]
    dst  = os.path.join(OUT_DIR, spec['filename'])
    if not force and os.path.exists(dst):
        print(f"\n[bg:{name}]  skipped (already exists — use --force to overwrite)")
        return
    print(f"\n[bg:{name}]  seed={spec['seed']}")
    t0 = time.time()
    src = call_sd(
        spec['prompt'], spec.get('negative', BASE_NEGATIVE),
        seed=spec['seed'],
        width=768, height=512, upscale=2,   # → 1536×1024 matches staticSceneData imageW/imageH
    )
    dst = os.path.join(OUT_DIR, spec['filename'])
    shutil.copy2(src, dst)
    kb = os.path.getsize(dst) // 1024
    print(f"  ✓ {dst}  ({kb} KB)  [{time.time()-t0:.0f}s]")


