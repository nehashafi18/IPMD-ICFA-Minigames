def derived_seed(level_name: str, object_id: str) -> int:
    """Deterministic seed: hash(level_seed + object_id) → int in [0, 2^31)."""
    base = LEVEL_SEEDS.get(level_name, 0)
    h    = hashlib.md5(f"{base}_{object_id}".encode()).hexdigest()
    return int(h[:8], 16) % (2 ** 31)


