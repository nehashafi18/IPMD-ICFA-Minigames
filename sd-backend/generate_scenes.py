def generate_object(name: str, force: bool = False) -> None:
    spec  = OBJECTS[name]
    dst   = os.path.join(OBJ_DIR, spec['filename'])
    if not force and os.path.exists(dst):
        print(f"\n[obj:{name}]  skipped (already exists — use --force to overwrite)")
        return
    seed  = derived_seed(spec['level'], name)
    print(f"\n[obj:{name}]  level={spec['level']}  seed={seed}")
    t0 = time.time()
    src_path = call_sd(
        spec['prompt'], spec['negative'],
        seed=seed,
        width=512, height=512, upscale=1,
    )
    raw     = Image.open(src_path).convert('RGB')
    # Add neutral buffer around SD output before rembg so the object is never
    # at the canvas edge when the model computes its alpha mask — avoids the
    # hard-cut antialiasing artifact at the circular rim.
    buf_px  = 48
    buffered = Image.new('RGB', (raw.width + buf_px*2, raw.height + buf_px*2), (230, 225, 215))
    buffered.paste(raw, (buf_px, buf_px))
    rgba    = remove_background(buffered)
    rgba    = pad_object(rgba)          # crop tight + square canvas with uniform margin
    dst     = os.path.join(OBJ_DIR, spec['filename'])
    rgba.save(dst, 'PNG', optimize=True)
    kb = os.path.getsize(dst) // 1024
    print(f"  ✓ {dst}  ({kb} KB)  [{time.time()-t0:.0f}s]")


