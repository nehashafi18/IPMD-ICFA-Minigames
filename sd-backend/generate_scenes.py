# ── Post-generation rebuild ──────────────────────────────────────────────────────
def rebuild_frontend() -> None:
    print(f"\n[build] Rebuilding frontend…")
    result = subprocess.run(
        ["npm", "run", "build"],
        cwd=FRONTEND_DIR,
        capture_output=True,
        text=True,
    )
    if result.returncode == 0:
        print("[build] ✓ dist updated")
    else:
        print(f"[build] ✗ failed (exit {result.returncode}):")
        print(result.stderr[-1500:])
        print("  Manual fix: cd frontend && npm run build")


# ── Entry point ──────────────────────────────────────────────────────────────────
def main() -> None:
    args  = sys.argv[1:]
    force = '--force' in args
    args  = [a for a in args if a != '--force']

    if args and args[0] == 'bg':
        name = args[1] if len(args) > 1 else None
        if name and name not in BACKGROUNDS:
            print(f"Unknown background '{name}'. Available: {', '.join(BACKGROUNDS)}")
            sys.exit(1)
        targets = [name] if name else list(BACKGROUNDS)
        for n in targets:
            generate_background(n, force=force)

    elif args and args[0] == 'obj':
        name = args[1] if len(args) > 1 else None
        if name and name not in OBJECTS:
            print(f"Unknown object '{name}'. Available: {', '.join(OBJECTS)}")
            sys.exit(1)
        targets = [name] if name else list(OBJECTS)
        for n in targets:
            generate_object(n, force=force)

    elif args and args[0] == 'gallery':
        name = args[1] if len(args) > 1 else None
        if name and name not in GALLERY_OBJECTS:
            print(f"Unknown gallery object '{name}'. Available: {', '.join(GALLERY_OBJECTS)}")
            sys.exit(1)
        targets = [name] if name else list(GALLERY_OBJECTS)
        for n in targets:
            generate_gallery_object(n, force=force)

    elif args and args[0] == 'gallery-bg':
        name = args[1] if len(args) > 1 else None
        if name and name not in GALLERY_BACKGROUNDS:
            print(f"Unknown gallery background '{name}'. Available: {', '.join(GALLERY_BACKGROUNDS)}")
            sys.exit(1)
        targets = [name] if name else list(GALLERY_BACKGROUNDS)
        for n in targets:
            generate_gallery_background(n, force=force)

    else:
        # No subcommand — generate everything, skipping existing files
        print("Generating all backgrounds…")
        for name in BACKGROUNDS:
            generate_background(name, force=force)
        print("\nGenerating all objects…")
        for name in OBJECTS:
            generate_object(name, force=force)

    rebuild_frontend()
    print("\nDone. Refresh browser to see new assets.")


if __name__ == "__main__":
    main()
